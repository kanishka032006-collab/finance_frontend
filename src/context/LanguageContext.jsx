export const useLanguage = () => useContext(LanguageContext);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('tridin-language') || 'en');
  useEffect(() => {
    localStorage.setItem('tridin-language', language);
    document.documentElement.lang = language === 'ta' ? 'ta' : language === 'hi' ? 'hi' : 'en';
    const dict = language === 'ta' ? ta : language === 'hi' ? hi : null;
    if (!dict) return undefined;

    // Translate known interface phrases while leaving entered form values untouched.
    const originals = new Map();
    const attrOriginals = new Map();
    const translateTextNode = (node) => {
      const raw = node.nodeValue;
      const normalized = raw.trim().replace(/\s+/g, ' ');
      if (!dict[normalized]) return;
      originals.set(node, raw);
      const leading = raw.match(/^\s*/)?.[0] || '';
      const trailing = raw.match(/\s*$/)?.[0] || '';
      node.nodeValue = `${leading}${dict[normalized]}${trailing}`;
    };
    const translate = (root) => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node;
      while ((node = walker.nextNode())) translateTextNode(node);
      const elements = [];
      if (root.nodeType === Node.ELEMENT_NODE && root.matches?.('[placeholder], [title], [aria-label]')) elements.push(root);
      elements.push(...(root.querySelectorAll?.('[placeholder], [title], [aria-label]') || []));
      elements.forEach((el) => {
        ['placeholder', 'title', 'aria-label'].forEach((attr) => {
          const value = el.getAttribute(attr);
          if (dict[value]) {
            if (!attrOriginals.has(el)) attrOriginals.set(el, {});
            attrOriginals.get(el)[attr] = value;
            el.setAttribute(attr, dict[value]);
          }
        });
      });
    };
    translate(document.body);
    const observer = new MutationObserver((records) => records.forEach(({ target, addedNodes, type }) => {
      if (type === 'attributes' && target.nodeType === Node.ELEMENT_NODE) translate(target);
      if (target.nodeType === Node.TEXT_NODE) {
        translateTextNode(target);
      }
      addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) translate(node);
        else if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      });
    }));
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] });
    return () => {
      observer.disconnect();
      originals.forEach((value, node) => { if (node.isConnected) node.nodeValue = value; });
      attrOriginals.forEach((values, el) => {
        if (el.isConnected) Object.entries(values).forEach(([attr, value]) => el.setAttribute(attr, value));
      });
    };
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

